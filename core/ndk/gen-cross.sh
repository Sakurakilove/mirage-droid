#!/usr/bin/env bash
# gen-cross.sh -- generate the Meson cross file + compiler/tool shims for an
# aarch64-linux-android (bionic) cross build with the Android NDK.
#
# The generated directory has two users:
#
#   * core/ndk/build-deps.sh   passes <out>/android-arm64.ini to `meson setup`
#     for glib and pixman (the file lists the target compilers directly, so no
#     wrapper scripts are needed there);
#   * core/ndk/build-qemu.sh   passes <out>/shim/ as QEMU's `--cross-prefix`.
#     QEMU's configure only knows prefixes (`<prefix>gcc`, `<prefix>pkg-config`,
#     ...), so every tool it may look up gets a tiny wrapper there.
#
# Usage:
#   Android NDK:  gen-cross.sh [--api 26] OUTDIR
# Environment:
#   ANDROID_NDK_ROOT (or ANDROID_NDK_HOME, NDK_ROOT)  -- NDK install root
#   DEPS                                              -- prefix with the
#                                                        cross-built glib,
#                                                        pixman and zlib.pc
#   MIRAGE_CCACHE=1                                   -- wrap the compilers
#                                                        with ccache when it
#                                                        is on PATH
#   CCACHE_DIR                                        -- passed through to ccache
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=versions.sh
. "$HERE/versions.sh"

API="${NDK_API:-26}"
while [ $# -gt 0 ]; do
    case "$1" in
        --api) API="$2"; shift 2 ;;
        -h|--help) sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) break ;;
    esac
done
OUT="${1:?usage: gen-cross.sh [--api N] OUTDIR}"

NDK="${ANDROID_NDK_ROOT:-${ANDROID_NDK_HOME:-${NDK_ROOT:-}}}"
[ -n "$NDK" ] || { echo "error: set ANDROID_NDK_ROOT to the Android NDK" >&2; exit 1; }
[ -d "$NDK/toolchains/llvm/prebuilt/linux-x86_64" ] || {
    echo "error: $NDK has no toolchains/llvm/prebuilt/linux-x86_64 (linux-x86_64 NDK only)" >&2
    exit 1
}
DEPS="${DEPS:?set DEPS to the cross-build dependency prefix}"

HOST_TAG=linux-x86_64
NDK_BIN="$NDK/toolchains/llvm/prebuilt/$HOST_TAG/bin"
SYSROOT="$NDK/toolchains/llvm/prebuilt/$HOST_TAG/sysroot"
TARGET="${NDK_TARGET}${API}"
CLANG="$NDK_BIN/clang"
CLANGXX="$NDK_BIN/clang++"
SYSROOT_LIB="$SYSROOT/usr/lib/${NDK_TARGET}"

for t in "$CLANG" "$CLANGXX" "$NDK_BIN/llvm-ar" "$SYSROOT"; do
    [ -e "$t" ] || { echo "error: missing $t (bad NDK?)" >&2; exit 1; }
done

CCACHE_PREFIX=""
if [ -n "${MIRAGE_CCACHE:-}" ] && command -v ccache >/dev/null 2>&1; then
    CCACHE_PREFIX="ccache "
fi

SHIM="$OUT/shim"
mkdir -p "$SHIM"

write_shim() {
    local name="$1"; shift
    {
        echo '#!/bin/sh'
        echo "# generated by core/ndk/gen-cross.sh -- do not edit"
        echo "exec $* \"\$@\""
    } > "$SHIM/$name"
    chmod +x "$SHIM/$name"
}

# --- compiler wrappers used by QEMU configure (--cross-prefix) --------------
# The target API level in the triple makes clang define __ANDROID_API__.
for name in gcc g++ cc c++ clang clang++; do
    case "$name" in
        g++|c++|clang++) write_shim "aarch64-linux-android-$name" "${CCACHE_PREFIX}\"$CLANGXX\" --target=$TARGET --sysroot=\"$SYSROOT\"" ;;
        *)               write_shim "aarch64-linux-android-$name" "${CCACHE_PREFIX}\"$CLANG\" --target=$TARGET --sysroot=\"$SYSROOT\"" ;;
    esac
done

# --- binutils wrappers -----------------------------------------------------
write_shim aarch64-linux-android-ar      "\"$NDK_BIN/llvm-ar\""
write_shim aarch64-linux-android-nm      "\"$NDK_BIN/llvm-nm\""
write_shim aarch64-linux-android-ranlib  "\"$NDK_BIN/llvm-ranlib\""
write_shim aarch64-linux-android-strip   "\"$NDK_BIN/llvm-strip\""
write_shim aarch64-linux-android-objcopy "\"$NDK_BIN/llvm-objcopy\""
write_shim aarch64-linux-android-objdump "\"$NDK_BIN/llvm-objdump\""
write_shim aarch64-linux-android-readelf "\"$NDK_BIN/llvm-readelf\""
write_shim aarch64-linux-android-as      "\"$CLANG\" --target=$TARGET --sysroot=\"$SYSROOT\" -c -x assembler"
if [ -e "$NDK_BIN/ld.lld" ]; then
    write_shim aarch64-linux-android-ld "\"$NDK_BIN/ld.lld\" --sysroot=\"$SYSROOT\""
fi

# --- pkg-config wrapper ----------------------------------------------------
# Only the cross-built dependencies (and the synthesised zlib.pc) may be seen:
# without PKG_CONFIG_LIBDIR a cross build can pick up the *build host's*
# x86_64 .pc files and silently link the wrong libraries.
write_shim aarch64-linux-android-pkg-config \
    "env PKG_CONFIG_LIBDIR=\"$DEPS/lib/pkgconfig:$DEPS/share/pkgconfig\" PKG_CONFIG_ALLOW_SYSTEM_CFLAGS=1 pkg-config"
# Meson also probes for a plain `pkg-config` in [binaries]; give it the same
# wrapper via the generated cross file (below), so no plain shim is needed.

# --- Meson cross file ------------------------------------------------------
# The glib cross-build needs a few facts Meson cannot obtain by running a
# target binary.  They are true for bionic (Android's libc):
#   * C99 vsnprintf/snprintf and Unix98 printf positionals are supported;
#   * va_list is copyable by value, like on all Linux ABIs;
#   * /proc/self/cmdline exists (glib uses it for g_get_prgname).
CROSS="$OUT/android-arm64.ini"
cat > "$CROSS" <<EOF
# generated by core/ndk/gen-cross.sh -- do not edit
# Android NDK $NDK_VERSION, API $API, $NDK_ABI

[binaries]
c = ['$CLANG', '--target=$TARGET', '--sysroot=$SYSROOT']
cpp = ['$CLANGXX', '--target=$TARGET', '--sysroot=$SYSROOT']
ar = ['$NDK_BIN/llvm-ar']
nm = ['$NDK_BIN/llvm-nm']
ranlib = ['$NDK_BIN/llvm-ranlib']
strip = ['$NDK_BIN/llvm-strip']
objcopy = ['$NDK_BIN/llvm-objcopy']
readelf = ['$NDK_BIN/llvm-readelf']
pkg-config = ['$SHIM/aarch64-linux-android-pkg-config']
pkgconfig = ['$SHIM/aarch64-linux-android-pkg-config']

[built-in options]
c_args = ['-O2', '-fPIC']
c_link_args = ['-Wl,-z,max-page-size=16384', '-Wl,-rpath,\$ORIGIN']

[host_machine]
system = 'linux'
cpu_family = 'aarch64'
cpu = 'aarch64'
endian = 'little'

[properties]
needs_exe_wrapper = true
# glib (cross-build facts, see above)
have_c99_vsnprintf = true
have_c99_snprintf = true
have_unix98_printf = true
va_val_copy = true
have_proc_self_cmdline = true
growing_stack = false
EOF

echo "wrote $CROSS"
echo "wrote shims in $SHIM (cross-prefix: $SHIM/aarch64-linux-android-)"
